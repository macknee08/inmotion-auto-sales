"""Builds js/data.js and optimized photos from the scraped MotorLot inventory.
Re-run after a fresh scrape:  python tests/build_data.py /path/to/inventory.json"""
import json, re, sys, os, glob
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else '/private/tmp/claude-501/inventory.json'
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, 'img', 'cars')            # downloaded originals
OUT = os.path.join(ROOT, 'img', 'v')               # optimized output
os.makedirs(OUT, exist_ok=True)

MODELS = {  # slug stem -> (make, model, body)
 '1997-bmw-3-series':('BMW','328i','Car'), '2005-chevrolet-trailblazer':('Chevrolet','TrailBlazer','SUV'),
 '2006-dodge-ram-1500':('Dodge','Ram 1500','Truck'), '2007-audi-a6':('Audi','A6','Car'),
 '2007-lexus-gs-450h':('Lexus','GS 450h','Car'), '2007-mercedes-benz-c-class':('Mercedes-Benz','C230','Car'),
 '2007-toyota-rav4':('Toyota','RAV4','SUV'), '2008-chevrolet-malibu':('Chevrolet','Malibu','Car'),
 '2008-mercedes-benz-cls-class':('Mercedes-Benz','CLS63 AMG','Car'), '2009-acura-tsx':('Acura','TSX','Car'),
 '2009-bmw-x5':('BMW','X5','SUV'), '2009-land-rover-range-rover-sport':('Land Rover','Range Rover Sport','SUV'),
 '2010-ford-f-150':('Ford','F-150','Truck'), '2010-jaguar-xf-series':('Jaguar','XF','Car'),
 '2010-toyota-tacoma':('Toyota','Tacoma','Truck'), '2011-lexus-rx-350':('Lexus','RX 350','SUV'),
 '2011-mercedes-benz-e-class':('Mercedes-Benz','E550','Car'), '2012-kia-forte':('Kia','Forte','Car'),
 '2012-kia-optima-hybrid':('Kia','Optima Hybrid','Car'), '2013-hyundai-equus':('Hyundai','Equus','Car'),
 '2014-infiniti-qx80':('Infiniti','QX80','SUV'), '2014-porsche-cayenne':('Porsche','Cayenne','SUV'),
 '2014-ram-1500':('RAM','1500','Truck'), '2015-chevrolet-equinox':('Chevrolet','Equinox','SUV'),
 '2015-chevrolet-tahoe':('Jaguar','F-Pace','SUV'),  # dealer listing slug mismatch; title says 2018 Jaguar F-Pace
 '2015-land-rover-lr4':('Land Rover','LR4','SUV'), '2015-land-rover-range-rover-evoque':('Land Rover','Range Rover Evoque','SUV'),
 '2015-lexus-is':('Lexus','IS 350','Car'), '2016-jeep-wrangler':('Jeep','Wrangler','SUV'),
 '2016-nissan-titan-xd':('Nissan','Titan XD','Truck'), '2016-porsche-macan':('Porsche','Macan','SUV'),
 '2017-gmc-acadia':('GMC','Acadia','SUV'), '2017-infiniti-q60':('Infiniti','Q60','Car'),
}
# Higgsfield 2K upscales replace the soft originals (key: slug, photo index)
UPSCALED = {('2016-porsche-macan-2437',0):'macan0', ('2016-porsche-macan-2437',1):'macan1',
            ('2016-porsche-macan-2437',2):'macan2', ('2016-porsche-macan-2437',5):'macan5',
            ('2016-nissan-titan-xd-2104',0):'titan'}
UP_DIR = '/private/tmp/claude-501/hf/up'

def num(s):
    d = re.sub(r'[^\d]', '', s or '')
    return int(d) if d else None

def save(img, base):
    img = img.convert('RGB')
    for w, q in ((1600, 80), (800, 76)):
        im = img.copy(); im.thumbnail((w, w), Image.LANCZOS)
        im.save(f'{base}-{w}.jpg', quality=q, optimize=True, progressive=True)
        im.save(f'{base}-{w}.webp', quality=q - 4, method=6)

cars = []
for v in json.load(open(SRC)):
    slug = v['slug']; stem = re.sub(r'-\d+$', '', slug)
    make, model, body = MODELS[stem]
    year = int(v['title'][:4])
    trim = v['title'][5:].replace(make, '', 1).strip()
    # trim = title minus "make model"
    for token in [model, model.replace(' ', '-')]:
        trim = trim.replace(token, '', 1)
    trim = re.sub(r'^(3-Series|C-Class|CLS-Class|E-Class|IS|RX|GS|Ram 1500)\s*', '', trim).strip(' -')
    trim = re.sub(r'^Series\s+', '', trim)
    photos = []
    for i, _ in enumerate(v['imgs']):
        src = os.path.join(RAW, f'{slug}-{i}.jpg')
        up = UPSCALED.get((slug, i))
        if up and os.path.exists(f'{UP_DIR}/{up}.png'):
            src = f'{UP_DIR}/{up}.png'
        base = os.path.join(OUT, f'{slug}-{i}')
        if not os.path.exists(base + '-800.webp') or up:
            save(Image.open(src), base)
        photos.append(f'{slug}-{i}')
    miles = num(v['miles'])
    cars.append(dict(
        id=v['stock'] or slug.split('-')[-1], slug=slug, year=year, make=make, model=model,
        trim=trim, body=body, price=num(v['price']), miles=miles if miles else None,
        trans=v['trans'], engine=v['engine'], fuel=v['fuel'],
        ext=(v['ext'] or '').strip().title() or None, int=(v['int'] or '').strip().title() or None,
        mpg=v['mpg'] or None, vin=v['vin'] or None,
        desc=v['desc'], features=v['features'][:14], photos=photos,
        url='https://www.inmotionautosales.com/inventory/' + slug))

cars.sort(key=lambda c: (0 if c['photos'] else 1, -(c['price'] or 0), -c['year']))
js = ('// Generated by tests/build_data.py from the dealer\'s live MotorLot listings. Do not hand-edit.\n'
      f'export const SCRAPED_AT = "{os.environ.get("SCRAPED_AT","")}";\n'
      'export const CARS = ' + json.dumps(cars, indent=1, ensure_ascii=False) + ';\n')
open(os.path.join(ROOT, 'js', 'data.js'), 'w').write(js)
print(len(cars), 'cars,', sum(len(c['photos']) for c in cars), 'photos')
for c in cars: print(c['year'], c['make'], c['model'], '|', c['trim'], '|', c['price'], c['miles'])
